/**
 * CodeMyFace V3 — SVG Document Serialization & Geometry Statistics
 *
 * Emits valid, structured, human-readable vector graphics with
 * semantic layer groupings, diagnostic styling, and precision control.
 */

import { VectorPath, Size2D, GeometryStats, BoundingBox } from './types';

/**
 * Serializes vector paths into a valid, standards-compliant SVG document
 */
export function serializeSvgDocument(
  paths: VectorPath[],
  viewport: Size2D = { width: 1000, height: 1000 },
  title: string = 'CodeMyFace V3 Vector Portrait'
): string {
  // Sort paths strictly by zIndex ascending
  const sorted = [...paths].sort((a, b) => a.zIndex - b.zIndex);

  let svg = `<?xml version="1.0" encoding="UTF-8"?>\n`;
  svg += `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${viewport.width} ${viewport.height}" width="100%" height="100%">\n`;
  svg += `  <title>${escapeXml(title)}</title>\n`;
  svg += `  <desc>Generated by CodeMyFace V3 High-Fidelity Geometry Engine</desc>\n`;
  svg += `  <!-- Background Canvas -->\n`;
  svg += `  <rect width="100%" height="100%" fill="#F7FAFC" />\n`;

  // Group by semantic regions
  const groups: Record<string, VectorPath[]> = {};
  for (let i = 0; i < sorted.length; i++) {
    const p = sorted[i];
    const key = p.semanticRegion || 'default';
    if (!groups[key]) groups[key] = [];
    groups[key].push(p);
  }

  for (const [region, regionPaths] of Object.entries(groups)) {
    svg += `  <g id="layer-${region}" data-semantic="${region}">\n`;
    for (let i = 0; i < regionPaths.length; i++) {
      const p = regionPaths[i];
      const fillAttr = p.fill ? `fill="${p.fill}"` : `fill="none"`;
      const strokeAttr = p.stroke ? `stroke="${p.stroke}"` : `stroke="none"`;
      const strokeWidthAttr = p.strokeWidth ? `stroke-width="${p.strokeWidth}"` : '';
      const linecapAttr = p.strokeLinecap ? `stroke-linecap="${p.strokeLinecap}"` : '';
      const linejoinAttr = p.strokeLinejoin ? `stroke-linejoin="${p.strokeLinejoin}"` : '';
      const opacityAttr = p.opacity !== undefined && p.opacity < 1.0 ? `opacity="${p.opacity}"` : '';

      const attrs = [
        `id="${p.id}"`,
        fillAttr,
        strokeAttr,
        strokeWidthAttr,
        linecapAttr,
        linejoinAttr,
        opacityAttr,
      ]
        .filter(Boolean)
        .join(' ');

      svg += `    <path ${attrs} d="${p.d}" />\n`;
    }
    svg += `  </g>\n`;
  }

  svg += `</svg>\n`;
  return svg;
}

/**
 * Computes exact geometric statistics for a set of paths
 */
export function computeGeometryStats(paths: VectorPath[], svgString?: string): GeometryStats {
  let totalNodes = 0;
  let totalBezierCurves = 0;
  let totalPolygons = 0;
  let minX = Infinity;
  let minY = Infinity;
  let maxX = -Infinity;
  let maxY = -Infinity;

  for (let i = 0; i < paths.length; i++) {
    const p = paths[i];
    totalNodes += p.points.length;
    if (p.segments) {
      totalBezierCurves += p.segments.length;
    } else {
      // Approximate curves from path d string
      const cMatches = p.d.match(/C/g);
      if (cMatches) totalBezierCurves += cMatches.length;
    }
    if (p.isClosed) totalPolygons++;

    for (let j = 0; j < p.points.length; j++) {
      const pt = p.points[j];
      if (pt.x < minX) minX = pt.x;
      if (pt.y < minY) minY = pt.y;
      if (pt.x > maxX) maxX = pt.x;
      if (pt.y > maxY) maxY = pt.y;
    }
  }

  const boundingBox: BoundingBox =
    paths.length > 0 && minX !== Infinity
      ? { minX, minY, maxX, maxY, width: maxX - minX, height: maxY - minY }
      : { minX: 0, minY: 0, maxX: 1000, maxY: 1000, width: 1000, height: 1000 };

  const totalAreaCovered = Math.round(boundingBox.width * boundingBox.height);
  const svgByteSize = svgString ? new TextEncoder().encode(svgString).length : 0;

  return {
    totalPaths: paths.length,
    totalNodes,
    totalBezierCurves,
    totalPolygons,
    totalAreaCovered,
    boundingBox,
    svgByteSize,
  };
}

function escapeXml(unsafe: string): string {
  return unsafe.replace(/[<>&'"]/g, (c) => {
    switch (c) {
      case '<':
        return '&lt;';
      case '>':
        return '&gt;';
      case '&':
        return '&amp;';
      case '\'':
        return '&apos;';
      case '"':
        return '&quot;';
      default:
        return c;
    }
  });
}
